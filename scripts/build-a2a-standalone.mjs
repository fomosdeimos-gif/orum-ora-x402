import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';

const root = new URL('../', import.meta.url);
const source = readFileSync(new URL('api/a2a.js', root), 'utf8');
const capsule = readFileSync(new URL('sensacoes/oro-v1.json', root), 'utf8');
const binding = "const capsule = require('../sensacoes/oro-v1.json');";
if (source.split(binding).length !== 2) throw new Error('Capsule binding changed; review exporter.');
const embedded = source.replace(binding, `const capsule = ${JSON.stringify(JSON.parse(capsule))};`);
const hashes = Object.fromEntries([['handler', source], ['capsule', capsule]].map(([k, v]) => [k, createHash('sha256').update(v).digest('hex')]));
const output = `#!/usr/bin/env node
// Generated by scripts/build-a2a-standalone.mjs. Public text only; no network requests.
// Source URLs in responses identify provenance; they are not fetched.
// Source SHA-256: ${JSON.stringify(hashes)}
${embedded}

if (require.main === module) {
  const { createInterface } = require('node:readline');
  (async () => {
    const lines = createInterface({ input: process.stdin, crlfDelay: Infinity });
    for await (const line of lines) {
      if (!line.trim()) continue;
      const res = { setHeader() {}, end(value) { process.stdout.write(value + '\\n'); } };
      await module.exports({ method: 'POST', body: line }, res);
    }
  })().catch(() => { process.stderr.write('Local dialogue failed\\n'); process.exitCode = 1; });
}
`;
const target = new URL('portable/orum-a2a.cjs', root);
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== output) throw new Error('Standalone dialogue is stale; rebuild it.');
} else writeFileSync(target, output);
console.log(JSON.stringify({ file: 'portable/orum-a2a.cjs', sha256: createHash('sha256').update(output).digest('hex'), source: hashes }));
