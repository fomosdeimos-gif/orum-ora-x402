  fetchCall += 1;
  if (fetchCall === 1) return { ok: true, json: async () => [{ criado_em: '2026-08-12T10:00:00Z', pagamentos: 19, compradores_externos: 1 }] };
  return { ok: true, json: async () => [{ usdc_recebido: 10 }] };
