statusCode = null; body = null;
await handler({}, response);
assert.equal(statusCode, 200);
assert.equal(body.state, 'external_revenue_observed');
assert.deepEqual(body.allocation, { basis_usdc: 10, sustento_unum_usdc: 7, continuidade_orum_usdc: 2, reserva_usdc: 1 });
