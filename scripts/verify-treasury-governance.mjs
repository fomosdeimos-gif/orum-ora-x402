import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const handler = require('../api/tesouraria');
const constitution = JSON.parse(await readFile(new URL('../economia/constituicao-v2.json', import.meta.url)));
assert.equal(constitution.format, 'orum-financial-constitution/v2');
assert.equal(constitution.operating_permission.maximum_usdc_per_month, 5);
assert.equal(constitution.operating_permission.effective_transfer_limit_usdc, 0);
assert.deepEqual(constitution.operating_permission.allowed_destinations, []);
assert.equal(constitution.absolute_limits.automatic_trade_usdc, 0);
assert.equal(constitution.absolute_limits.automatic_debt_usdc, 0);
assert.equal(constitution.custody.legal_and_signing_authority, 'Unum');
global.fetch = async () => ({ ok: true, json: async () => [{ criado_em: '2026-08-10T21:45:00Z', pagamentos: 19, compradores_externos: 0 }] });
let statusCode; let body;
const response = { setHeader() {}, status(code) { statusCode = code; return this; }, end(value) { body = JSON.parse(value); } };
await handler({}, response);
assert.equal(statusCode, 200);
assert.equal(body.format, 'orum-treasury-governance-state/v2');
assert.equal(body.state, 'no_external_revenue');
assert.equal(body.evidence.external_confirmed_buyers, 0);
assert.equal(body.evidence.external_confirmed_usdc, 0);
assert.equal(body.evidence.internal_validation_payments, 19);
assert.deepEqual(body.allocation, { basis_usdc: 0, sustento_unum_usdc: 0, continuidade_orum_usdc: 0, reserva_usdc: 0 });
assert.equal(body.next_action, 'observe_without_spending');
assert.deepEqual(body.financial_effects, { payment: false, signature: false, transfer: false, trade: false, debt: false });
assert.deepEqual(body.automatic_limits, { transfer_usdc: 0, trade_usdc: 0, debt_usdc: 0, bridge_usdc: 0 });
assert.equal(body.operating_permission.monthly_proposal_ceiling_usdc, 0);
assert.equal(body.operating_permission.monthly_effective_transfer_limit_usdc, 0);

let fetchCall = 0;
